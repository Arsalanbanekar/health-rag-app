/**
 * Get translation function for a given language code.
 * Falls back to English if key is missing.
 */
export function getTranslations(langCode = 'en') {
  return translations[langCode] || translations.en;
}

/**
 * Get the LLM-friendly language name from a language code.
 */
export function getLLMLanguage(langCode = 'en') {
  return LLM_LANG_MAP[langCode] || 'English';
}
